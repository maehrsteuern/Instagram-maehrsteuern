# ---------- helpers ----------

def esc(text):
    return html.escape(str(text), quote=True)


def md(text):
    """Inline Markdown from STATUS.md building blocks → HTML (`code`, **bold**, [link](url))."""
    codes = []

    def keep(m):
        codes.append(f"<code>{m.group(1)}</code>")
        return f"\x00{len(codes) - 1}\x00"
    t = re.sub(r"`([^`]+)`", keep, esc(text))
    t = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", t)
    t = re.sub(r"\[([^\]]+)\]\((https?://[^)\s]+)\)", r'<a href="\2" target="_blank" rel="noopener">\1</a>', t)
    return re.sub(r"\x00(\d+)\x00", lambda m: codes[int(m.group(1))], t)


def level(s):
    """Status → display level (color always comes together with symbol + text)."""
    if s == "approved":
        return "ok"
    if s == "published":
        return "done"
    if s == "error":
        return "crit"
    if s == "cancelled":
        return "muted"
    if s == "manual":
        return "info"
    return "warn"  # draft, waiting_*


def pill(s):
    return f'<span class="pill {level(s)}">{esc(status({"status": s}))}</span>'


def point_level(p):
    if p.startswith("🔴"):
        return "crit"
    if p.startswith(("👉", "Nothing")):
        return "info"
    return "warn"


