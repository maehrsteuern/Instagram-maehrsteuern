def tiles(n, points, upcoming, workflows):
    rows = list(csv.DictReader(ACCOUNT.open())) if ACCOUNT.exists() else []
    followers, diff_text = "–", ""
    if rows:
        followers = f'{int(rows[-1]["followers_count"]):,}'
        if len(rows) > 1:
            diff = int(rows[-1]["followers_count"]) - int(rows[-2]["followers_count"])
            diff_text = f'<span class="delta {"neg" if diff < 0 else "pos" if diff > 0 else ""}">{diff:+d} since {esc(short_date(rows[-2]["date"]))}</span>'
    reach, reach_text = "–", ""
    if (files := insights_files()):
        days = sorted((json.loads(files[-1].read_text()).get("daily_reach") or {}).items())
        if days:
            reach = f"{days[-1][1]:,}"
            reach_text = f'<span class="delta">on {short_date(days[-1][0])} · 7-day avg {round(sum(v for _, v in days[-7:]) / len(days[-7:])):,}</span>'
    week = [x for x in upcoming if planned(x) <= n + timedelta(days=7)]
    open_ = [p for p in points if not p.startswith("Nothing")]
    red = sum(p.startswith("🔴") for p in open_)
    ok = sum(l.startswith("✅") for _, _, l in workflows)
    failed = sum(l.startswith("🔴") for _, _, l in workflows)
    auto_text = f"{failed} failed" if failed else ("all ok" if ok else "status only visible in Actions")
    return f'''<section class="tiles">
  <div class="tile"><div class="t-label">Followers</div><div class="t-value">{esc(followers)}</div>{diff_text}</div>
  <div class="tile"><div class="t-label">Reach (last day)</div><div class="t-value">{esc(reach)}</div>{reach_text}</div>
  <div class="tile"><div class="t-label">Planned · next 7 days</div><div class="t-value">{len(week)}</div>
    <span class="delta">{sum(x["status"] == "approved" for x in week)} approved</span></div>
  <div class="tile {"t-warn" if open_ else ""}"><div class="t-label">Needs you</div><div class="t-value">{len(open_)}</div>
    <span class="delta {"neg" if red else ""}">{f"{red} red" if red else "nothing urgent"}</span></div>
  <div class="tile {"t-crit" if failed else ""}"><div class="t-label">Automation</div><div class="t-value">{ok}/{len(workflows)}</div>
    <span class="delta {"neg" if failed else ""}">{esc(auto_text)}</span></div>
</section>'''


def needs(points):
    li = "".join(f'<li class="card {point_level(p)}">{md(p)}</li>' for p in points)
    return f'<section id="needs"><h2>👉 Needs you</h2><ul class="cards">{li}</ul></section>'


def notes():
    if not NOTES.exists() or not (text := NOTES.read_text().strip()):
        return ""
    out, in_list = [], False
    for line in text.splitlines():
        if m := re.match(r"\s*[-*] (.*)", line):
            if not in_list:
                out.append("<ul class='notes'>")
                in_list = True
            out.append(f"<li>{md(m.group(1))}</li>")
        elif line.strip():
            if in_list:
                out.append("</ul>")
                in_list = False
            out.append(f"<p>{md(line.lstrip('# '))}</p>")
    if in_list:
        out.append("</ul>")
    return f'<section id="progress"><h2>📝 In progress</h2><div class="block">{"".join(out)}</div></section>'


def calendar(n, entries):
    """Four weeks starting Sunday of this week (US calendar), every entry as a chip with time, type and status."""
    start = n.date() - timedelta(days=(n.weekday() + 1) % 7)
    days = [start + timedelta(days=i) for i in range(28)]
    by_day = {}
    for x in entries:
        if x["status"] != "cancelled":
            by_day.setdefault(planned(x).date(), []).append(x)
    cells = "".join(f'<div class="cal-head">{w}</div>' for w in SUNDAY_FIRST)
    for d in days:
        chips = "".join(
            f'<div class="chip {level(x["status"])}" title="{esc(x["id"])} · {esc(status(x))}">'
            f'<span class="chip-time">{clock(planned(x))}</span> {esc(TYPE.get(x["type"], x["type"]).split(" ")[0])} '
            f'<span class="chip-id">{esc(x["id"])}</span></div>'
            for x in sorted(by_day.get(d, []), key=planned))
        cls = "cal-day" + (" today" if d == n.date() else "") + (" past" if d < n.date() else "")
        cells += f'<div class="{cls}"><div class="cal-date">{WEEKDAY[d.weekday()]} {d.month}/{d.day}</div>{chips}</div>'
    legend = "".join(f'<span class="pill {s}">{t}</span>' for s, t in (
        ("done", "✅ published"), ("ok", "🟢 approved"), ("warn", "🟡 draft / ⏳ waiting"),
        ("info", "✋ by hand"), ("crit", "🔴 error")))
    return f'''<section id="calendar"><h2>🗓️ Calendar – 4 weeks <span class="quiet">(times ET)</span></h2>
<div class="legend">{legend}</div>
<div class="cal-scroll"><div class="cal">{cells}</div></div></section>'''


def plan_table(n, upcoming):
    week = sorted((x for x in upcoming if planned(x) <= n + timedelta(days=7)), key=planned)
    later = sorted((x for x in upcoming if planned(x) > n + timedelta(days=7)), key=planned)

    def rows(items):
        return "".join(
            f'<tr><td class="nowrap">{esc(when(planned(x)))}</td><td class="nowrap">{esc(TYPE.get(x["type"], x["type"]))}<br><code>{esc(x["id"])}</code></td>'
            f'<td>{pill(x["status"])}</td><td class="note">{md(x.get("note", "") + issue_link(x))}</td></tr>'
            for x in items) or '<tr><td colspan="4">Nothing planned.</td></tr>'
    head = "<thead><tr><th>When (ET)</th><th>What</th><th>Status</th><th>Note</th></tr></thead>"
    parts = [f'<section id="plan"><h2>⏭️ Next 7 days</h2><div class="tab-scroll"><table>{head}<tbody>{rows(week)}</tbody></table></div>']
    if later:
        parts.append(f'<h3>Later</h3><div class="tab-scroll"><table>{head}<tbody>{rows(later)}</tbody></table></div>')
    return "".join(parts) + "</section>"


def recent(entries):
    done = sorted((x for x in entries if x["status"] == "published"), key=planned, reverse=True)[:10]
    if not done:
        return ""
    li = "".join(
        f'<li><span class="nowrap">{esc(when(planned(x)))}</span> · {esc(TYPE.get(x["type"], x["type"]))} <code>{esc(x["id"])}</code>'
        + (f' · <a href="{esc(x["link"])}" target="_blank" rel="noopener">view ↗</a>' if x.get("link") else "") + "</li>"
        for x in done)
    return f'<section><h2>✅ Recently published</h2><ul class="list">{li}</ul></section>'


def bars(values, height=180):
    """Column chart (one series) as SVG; hover tooltip via data-tip."""
    if not values:
        return ""
    width, left, bottom, top_pad = 1100, 40, 22, 8
    high = max(v for _, v in values) or 1
    step = next(s for s in (1, 2, 5, 10, 20, 25, 50, 100, 200, 250, 500, 1000, 2000, 5000, 10**9) if high / s <= 4)
    top = -(-high // step) * step
    y = lambda v: top_pad + (height - top_pad - bottom) * (1 - v / top)
    slot = (width - left) / len(values)
    parts = [f'<svg class="chart" viewBox="0 0 {width} {height}" role="img" aria-label="Reach per day">']
    for t in range(0, top + 1, step):
        parts.append(f'<line class="grid" x1="{left}" x2="{width}" y1="{y(t):.1f}" y2="{y(t):.1f}"/>'
                     f'<text class="axis" x="{left - 6}" y="{y(t) + 4:.1f}" text-anchor="end">{t:,}</text>')
    b = max(2, min(18, slot - 2))
    every = max(1, len(values) // 8)
    for i, (d, v) in enumerate(values):
        x = left + i * slot + (slot - b) / 2
        h = max(0.0, (height - bottom) - y(v))
        rad = min(4, b / 2, h)
        tip = f"{short_date(d)}: {v:,} reached"
        parts.append(f'<rect class="hit" x="{left + i * slot:.1f}" y="{top_pad}" width="{slot:.1f}" height="{height - top_pad - bottom}" data-tip="{esc(tip)}"/>')
        if h > 0:
            parts.append(f'<path class="bar" d="M{x:.1f},{height - bottom} v{-(h - rad):.1f} q0,{-rad:.1f} {rad:.1f},{-rad:.1f} '
                         f'h{b - 2 * rad:.1f} q{rad:.1f},0 {rad:.1f},{rad:.1f} v{h - rad:.1f} z" pointer-events="none"/>')
        if (i % every == 0 and len(values) - 1 - i >= every / 2) or i == len(values) - 1:
            parts.append(f'<text class="axis" x="{x + b / 2:.1f}" y="{height - 6}" text-anchor="middle">{short_date(d)}</text>')
    last = values[-1]
    parts.append(f'<text class="value" x="{left + (len(values) - 0.5) * slot:.1f}" y="{y(last[1]) - 6:.1f}" text-anchor="end">{last[1]:,}</text>')
    return "".join(parts) + "</svg>"


def line(points, height=150):
    """Follower trend as a line (one series), dots ≥ 8 px, hover tooltip."""
    if len(points) < 2:
        return ""
    width, left, bottom, top_pad = 1100, 46, 22, 16
    values = [v for _, v in points]
    lo, hi = min(values), max(values)
    if hi - lo < 4:
        lo, hi = lo - 2, hi + 2
    y = lambda v: top_pad + (height - top_pad - bottom) * (1 - (v - lo) / (hi - lo))
    x = lambda i: left + 10 + (width - left - 20) * i / (len(points) - 1)
    parts = [f'<svg class="chart" viewBox="0 0 {width} {height}" role="img" aria-label="Follower trend">']
    for t in (lo, (lo + hi) / 2, hi):
        parts.append(f'<line class="grid" x1="{left}" x2="{width}" y1="{y(t):.1f}" y2="{y(t):.1f}"/>'
                     f'<text class="axis" x="{left - 6}" y="{y(t) + 4:.1f}" text-anchor="end">{round(t):,}</text>')
    path = " ".join(f"{'M' if i == 0 else 'L'}{x(i):.1f},{y(v):.1f}" for i, (_, v) in enumerate(points))
    parts.append(f'<path class="line" d="{path}"/>')
    every = max(1, len(points) // 8)
    for i, (d, v) in enumerate(points):
        parts.append(f'<circle class="dot" cx="{x(i):.1f}" cy="{y(v):.1f}" r="4.5"/>'
                     f'<circle class="hit" cx="{x(i):.1f}" cy="{y(v):.1f}" r="14" data-tip="{esc(f"{short_date(d)}: {v:,} followers")}"/>')
        if (i % every == 0 and len(points) - 1 - i >= every / 2) or i == len(points) - 1:
            parts.append(f'<text class="axis" x="{x(i):.1f}" y="{height - 6}" text-anchor="middle">{short_date(d)}</text>')
    parts.append(f'<text class="value" x="{x(len(points) - 1):.1f}" y="{y(points[-1][1]) - 10:.1f}" text-anchor="end">{points[-1][1]:,}</text>')
    return "".join(parts) + "</svg>"


def numbers(n):
    rows = list(csv.DictReader(ACCOUNT.open())) if ACCOUNT.exists() else []
    files = insights_files()
    if not rows and not files:
        return ('<section id="numbers"><h2>📈 Numbers</h2><p>No stats yet – they start after the Instagram secrets are set '
                'and the first stats run (daily around 9:00 AM ET).</p></section>')
    parts = ['<section id="numbers"><h2>📈 Numbers <span class="quiet">(daily around 9:00 AM ET)</span></h2><div class="stack">']
    if files:
        d = json.loads(files[-1].read_text())
        days = sorted((d.get("daily_reach") or {}).items())[-30:]
        parts.append(f'<figure class="block"><figcaption>Reach per day · last {len(days)} days</figcaption>{bars(days)}</figure>')
    if rows:
        parts.append(f'<figure class="block"><figcaption>Followers</figcaption>'
                     f'{line([(z["date"], int(z["followers_count"])) for z in rows][-60:])}</figure>')
    parts.append("</div>")
    if files:
        d = json.loads(files[-1].read_text())
        old = {b["id"]: b for b in json.loads(files[-2].read_text()).get("media", [])} if len(files) > 1 else {}
        new = [b for b in d.get("media", []) if b.get("timestamp") and n - local(b["timestamp"]) < timedelta(days=14)]
        if new:
            body = ""
            for b in sorted(new, key=lambda x: x["timestamp"], reverse=True):
                plus = (f' <span class="quiet">(+{b["views"] - old[b["id"]]["views"]})</span>'
                        if isinstance(old.get(b["id"], {}).get("views"), int) and isinstance(b.get("views"), int) else "")
                name = (b.get("caption") or "").split("\n")[0][:50]
                body += (f'<tr><td><span class="nowrap">{esc(when(local(b["timestamp"])))}</span><br>'
                         f'<a href="{esc(b.get("permalink", ""))}" target="_blank" rel="noopener">{esc(name)}</a></td>'
                         + "".join(f'<td class="num">{esc(b.get(k, "–"))}{plus if k == "views" else ""}</td>'
                                   for k in ("views", "reach", "likes", "comments", "saved", "shares")) + "</tr>")
            parts.append('<h3>Posts (last 14 days)</h3><div class="tab-scroll"><table><thead><tr><th>Post</th>'
                         '<th class="num">Views</th><th class="num">Reach</th><th class="num">Likes</th><th class="num">Comments</th>'
                         f'<th class="num">Saves</th><th class="num">Shares</th></tr></thead><tbody>{body}</tbody></table></div>')
        stories = sorted((s for s in d.get("active_stories") or [] if s.get("time")), key=lambda x: x["time"])
        if stories:
            body = "".join(
                f'<tr><td class="nowrap">{esc(when(local(s["time"])))}</td>'
                + "".join(f'<td class="num">{esc(s.get(k, "–"))}</td>' for k in ("views", "reach", "replies", "profile_visits", "follows"))
                + "</tr>" for s in stories)
            parts.append('<h3>Stories (last 24 h)</h3><div class="tab-scroll"><table><thead><tr><th>Story</th><th class="num">Views</th>'
                         '<th class="num">Reach</th><th class="num">Replies</th><th class="num">Profile visits</th>'
                         f'<th class="num">Follows</th></tr></thead><tbody>{body}</tbody></table></div>')
    parts.append('<p class="quiet">Raw data: <code>automation/stats/</code> · analysis: <code>strategy/06_analytics.md</code></p></section>')
    return "".join(parts)


def automation(workflows):
    cards = ""
    for name, schedule, last in workflows:
        s = "crit" if last.startswith("🔴") else "ok" if last.startswith("✅") else "muted"
        cards += f'<div class="wf {s}"><div class="wf-name">{esc(name)}</div><div class="wf-when">{esc(schedule)}</div><div class="wf-status">{md(last)}</div></div>'
    hint = ("" if any(l != "–" for _, _, l in workflows) else
            '<p class="quiet">No runs yet (or no GH_TOKEN locally) – the status is visible under Actions once the repo is live.</p>')
    return f'<section id="automation"><h2>⚙️ Automation</h2><div class="wfs">{cards}</div>{hint}</section>'


def log(n, commits):
    counts = {}
    for c in commits:
        counts[c["kind"]] = counts.get(c["kind"], 0) + 1
    filters = '<button class="filt active" data-kind="">All <span>{}</span></button>'.format(len(commits)) + "".join(
        f'<button class="filt" data-kind="{esc(a)}">{esc(a)} {esc(KIND_NAME.get(a, ""))} <span>{z}</span></button>'
        for a, z in sorted(counts.items(), key=lambda kv: -kv[1]))
    days = {}
    for c in commits:
        days.setdefault(c["time"].date(), []).append(c)
    blocks = ""
    for d, items in days.items():
        lis = ""
        for c in items:
            details = ("Plan: " + "; ".join(c["plan"])) if c["plan"] else ", ".join(f"`{x}`" for x in c["areas"])
            search = (c["message"] + " " + details).lower()
            lis += (f'<li class="lg" data-kind="{esc(c["kind"])}" data-search="{esc(search)}">'
                    f'<span class="lg-time">{clock(c["time"])}</span><span class="lg-kind" title="{esc(KIND_NAME.get(c["kind"], ""))}">{esc(c["kind"])}</span>'
                    f'<div class="lg-text"><div>{esc(c["message"])} <a class="sha" href="https://github.com/{REPO}/commit/{c["sha"]}" '
                    f'target="_blank" rel="noopener">{c["sha"][:7]}</a></div>'
                    + (f'<div class="lg-details">{md(details)}</div>' if details else "") + "</div></li>")
        is_open = " open" if (n.date() - d).days < 7 else ""
        blocks += (f'<details class="lg-day"{is_open}><summary>{WEEKDAY[d.weekday()]} {d.month}/{d.day}/{d.year} '
                   f'<span class="quiet">· {len(items)}</span></summary><ul class="lg-list">{lis}</ul></details>')
    return f'''<section id="log"><h2>📜 Log – every change</h2>
<div class="lg-tools"><input type="search" id="lg-search" placeholder="Search (e.g. Reel, Radar, 04-…)" aria-label="Search the log">
<div class="filter">{filters}</div></div>
<div id="lg">{blocks}</div><p id="lg-empty" class="quiet" hidden>Nothing found.</p></section>'''


